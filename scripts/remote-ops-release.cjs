'use strict';
const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const run = (cmd, args, options = {}) => execFileSync(cmd, args, { encoding: 'utf8', timeout: 600000, ...options }).trim();
const base = 'localhost/lilly-team-release:8e3e42246bcbbd7f';
const revision = process.argv[2];
assert.match(revision, /^[a-f0-9]{40}$/);
const root = `/tmp/lilly-remote-ops-${revision.slice(0, 12)}`;
const source = `${root}/source`;
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
fs.mkdirSync(root, { recursive: true });
if (!fs.existsSync(source)) run('git', ['clone', '--depth=1', 'https://github.com/philly1084/Lilly.git', source]);
assert.equal(run('git', ['rev-parse', 'HEAD'], { cwd: source }), revision);
const before = JSON.parse(run('kubectl', ['-n', 'kimibuilt', 'get', 'deployment/backend', '-o', 'json']));
assert.equal(before.spec.template.spec.containers.find(c => c.name === 'backend').image, base);
fs.writeFileSync(`${root}/before.json`, JSON.stringify(before), { mode: 0o600 });
const liveHash = run('kubectl', ['-n', 'kimibuilt', 'exec', 'deployment/backend', '--', 'sha256sum', '/app/src/routes/tools.js']).split(/\s/)[0];
assert.equal(liveHash, '268a44d6fd565b1a8e4f6eb266f264abb2e8fd3bbc0bc5980c60540b220bac48');
const disk = fs.statfsSync('/tmp', { bigint: true });
// Stream the existing base layers straight to containerd; no duplicate image archive.
assert.ok(disk.bavail * disk.bsize > disk.blocks * disk.bsize * 15n / 100n + 1024n ** 3n, 'Insufficient disk reserve');
const context = `${root}/context`;
fs.mkdirSync(context, { recursive: true });
const files = ['tools.js', 'remote-ops-contract.js'];
for (const file of files) fs.copyFileSync(`${source}/src/routes/${file}`, `${context}/${file}`);
fs.writeFileSync(`${context}/Dockerfile`, `FROM ${base}\nCOPY --chown=1001:1001 tools.js remote-ops-contract.js /app/src/routes/\n`);
const image = `localhost/lilly-remote-ops:${revision.slice(0, 12)}`;
run('docker', ['build', '--network=none', '-t', image, context], { stdio: 'inherit' });
run('docker', ['run', '--rm', '--network=none', '--entrypoint=node', image, '--check', '/app/src/routes/tools.js']);
run('bash', ['-o', 'pipefail', '-c', `docker save --format oci-archive ${image} | k3s ctr images import -`], { stdio: 'inherit' });
fs.writeFileSync(`${root}/receipt.json`, JSON.stringify({ revision, image, base, files: Object.fromEntries(files.map(f => [f, hash(fs.readFileSync(`${context}/${f}`))])) }, null, 2));
run('node', ['scripts/k3s-deployment-coordinator.js', 'deploy-backend', '--expected-image', base, '--image', image, '--image-pull-policy', 'IfNotPresent', '--source-sha', revision], { cwd: source, stdio: 'inherit' });
const after = JSON.parse(run('kubectl', ['-n', 'kimibuilt', 'get', 'deployment/backend', '-o', 'json']));
const expected = structuredClone(before.spec);
const index = expected.template.spec.containers.findIndex(c => c.name === 'backend');
expected.template.spec.containers[index].image = image;
expected.template.spec.containers[index].imagePullPolicy = 'IfNotPresent';
expected.template.metadata.annotations = after.spec.template.metadata.annotations;
assert.deepEqual(after.spec, expected);
for (const f of files) assert.equal(run('kubectl', ['-n', 'kimibuilt', 'exec', 'deployment/backend', '--', 'sha256sum', `/app/src/routes/${f}`]).split(/\s/)[0], hash(fs.readFileSync(`${context}/${f}`)));
console.log(JSON.stringify({ root, image, preservedDeploymentSpec: true, servedSourceHashesMatch: true }));
